"""Inventory of Win32 API usage per function for phase-1 core extraction (P1-01).

Usage: python -I tools/win32-api-inventory.py <file.cpp>... > docs/core-win32-api-inventory.md
Heuristic: Win32 calls in Notepad++ sources are written with a leading '::' (e.g. ::GetFileAttributesEx).
Also counts Win32-only types (HWND, HFONT, ...) and MS CRT wide functions.
"""
import re, sys, collections, pathlib

CALL = re.compile(r'(?<![\w:])::([A-Z][A-Za-z0-9_]+)\s*\(')
TYPES = re.compile(r'\b(HWND|HINSTANCE|HFONT|HBRUSH|HDC|HICON|HMENU|HKEY|COLORREF|RECT|POINT|LOGFONT|WPARAM|LPARAM|LRESULT|BOOL|DWORD|UINT|TCHAR|WCHAR|MAX_PATH|CSIDL_\w+)\b')
CRT = re.compile(r'\b(_wcs\w+|_wto\w+|wcscpy_s|wcscat_s|wcsncpy_s|swprintf_s|_snwprintf\w*|_wfopen\w*|_itow\w*|_ultow\w*|_wsplitpath\w*|wcstombs|mbstowcs)\s*\(')
FUNC = re.compile(r'^(?:[\w:<>,\*&\s]+?)\b([\w]+::[~\w]+|\w+)\s*\([^;]*\)\s*(?:const)?\s*(?:noexcept)?\s*\{?\s*$')

def scan(path):
    text = pathlib.Path(path).read_text(encoding='utf-8', errors='replace').splitlines()
    func, depth = '(file scope)', 0
    per_func = collections.defaultdict(collections.Counter)
    totals = collections.Counter(); types = collections.Counter(); crt = collections.Counter()
    for line in text:
        s = line.strip()
        if depth == 0:
            m = FUNC.match(s)
            if m and not s.startswith(('if', 'for', 'while', 'switch', 'return', '#', '//')):
                func = m.group(1)
        for m in CALL.finditer(line):
            per_func[func][m.group(1)] += 1; totals[m.group(1)] += 1
        for m in TYPES.finditer(line): types[m.group(1)] += 1
        for m in CRT.finditer(line): crt[m.group(1)] += 1; per_func[func]['CRT:' + m.group(1)] += 1
        depth += line.count('{') - line.count('}')
        if depth <= 0: depth = 0
    return per_func, totals, types, crt

print('# Core extraction: Win32 API inventory\n')
print('Generated by `tools/win32-api-inventory.py` (phase 1, P1-01). Heuristic: `::Api(` calls, Win32 types, MS CRT wide functions.\n')
for path in sys.argv[1:]:
    per_func, totals, types, crt = scan(path)
    print(f'## `{path}`\n')
    print(f'- Win32 calls: {sum(totals.values())} ({len(totals)} distinct), MS CRT wide calls: {sum(crt.values())}, Win32 type mentions: {sum(types.values())}\n')
    print('| API | count |\n|---|---|')
    for api, n in totals.most_common(): print(f'| `{api}` | {n} |')
    if crt:
        print('\n| MS CRT | count |\n|---|---|')
        for api, n in crt.most_common(): print(f'| `{api}` | {n} |')
    if types:
        print('\n| Win32 type | count |\n|---|---|')
        for t, n in types.most_common(): print(f'| `{t}` | {n} |')
    print('\n### Per function\n\n| function | Win32 / CRT calls |\n|---|---|')
    for f, c in sorted(per_func.items(), key=lambda kv: -sum(kv[1].values())):
        print(f'| `{f}` | ' + ', '.join(f'{k}×{v}' if v > 1 else k for k, v in c.most_common()) + ' |')
    print()
