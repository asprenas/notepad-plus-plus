"""Generates the main menu definition and command ids for the Qt UI (phase 2, P2-01).

Usage (from the repository root):  python -I tools/gen-menu-table.py

Outputs:
  app/ui/menu/CommandIds.h     constexpr ids of every IDM_* in menuCmdID.h (values = upstream)
  app/ui/menu/MainMenu.inc     the IDR_M30_MENU tree of Notepad_plus.rc as X-macros:
      NPP_POPUP_BEGIN("text") / NPP_POPUP_END() / NPP_ITEM("text", IDM_X) / NPP_SEPARATOR()
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "PowerEditor/src"
out_dir = root / "app/ui/menu"
out_dir.mkdir(parents=True, exist_ok=True)

# --- ids ------------------------------------------------------------------------------------
defs = {}
for line in (src / "menuCmdID.h").read_text(encoding="utf-8", errors="replace").splitlines():
    line = re.sub(r"//.*", "", line)
    m = re.match(r"\s*#define\s+(IDM\w*)\s+(.+?)\s*$", line)
    if m:
        defs[m.group(1)] = m.group(2)

values = {}


def value(name, depth=0):
    if name in values:
        return values[name]
    if depth > 20 or name not in defs:
        raise KeyError(name)
    expr = defs[name]
    expr2 = re.sub(r"\b(IDM\w*)\b", lambda m: str(value(m.group(1), depth + 1)), expr)
    v = int(eval(expr2, {"__builtins__": {}}))
    values[name] = v
    return v


for n in defs:
    try:
        value(n)
    except Exception:
        pass

ids = ["// GENERATED by tools/gen-menu-table.py from PowerEditor/src/menuCmdID.h. Do not edit.",
       "#pragma once", "", "namespace npp::ui::cmd {", ""]
for n in sorted(values, key=lambda k: (values[k], k)):
    ids.append(f"inline constexpr int {n} = {values[n]};")
ids += ["", "} // namespace npp::ui::cmd", ""]
(out_dir / "CommandIds.h").write_text("\n".join(ids), encoding="utf-8", newline="\n")

# --- menu tree ------------------------------------------------------------------------------
rc = (src / "Notepad_plus.rc").read_text(encoding="utf-8", errors="replace").splitlines()
start = next(i for i, l in enumerate(rc) if l.startswith("IDR_M30_MENU MENU"))
out = ["// GENERATED by tools/gen-menu-table.py from PowerEditor/src/Notepad_plus.rc (IDR_M30_MENU). Do not edit."]
depth = 0
unknown = set()
for line in rc[start + 1:]:
    s = line.strip()
    if s.startswith("//") or not s:
        continue
    if s == "BEGIN":
        depth += 1
        continue
    if s == "END":
        depth -= 1
        if depth == 0:
            break
        out.append("NPP_POPUP_END()")
        continue
    m = re.match(r'POPUP\s+"((?:[^"]|"")*)"', s)
    if m:
        out.append(f'NPP_POPUP_BEGIN("{m.group(1)}")')
        continue
    if s.startswith("MENUITEM SEPARATOR"):
        out.append("NPP_SEPARATOR()")
        continue
    m = re.match(r'MENUITEM\s+"((?:[^"]|"")*)"\s*,\s*(\w+)', s)
    if m:
        text = m.group(1).replace('""', '\\"')
        ident = m.group(2)
        if ident not in values:
            unknown.add(ident)
            continue
        out.append(f'NPP_ITEM("{text}", {ident})')
(out_dir / "MainMenu.inc").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")

# --- default shortcuts (Parameters.cpp winKeyDefs / scintKeyDefs) ------------------------------
VK = {"VK_NULL": 0, "VK_BACK": 0x08, "VK_TAB": 0x09, "VK_RETURN": 0x0D, "VK_ESCAPE": 0x1B, "VK_SPACE": 0x20,
      "VK_PRIOR": 0x21, "VK_NEXT": 0x22, "VK_END": 0x23, "VK_HOME": 0x24, "VK_LEFT": 0x25, "VK_UP": 0x26,
      "VK_RIGHT": 0x27, "VK_DOWN": 0x28, "VK_INSERT": 0x2D, "VK_DELETE": 0x2E, "VK_MULTIPLY": 0x6A,
      "VK_ADD": 0x6B, "VK_SUBTRACT": 0x6D, "VK_DECIMAL": 0x6E, "VK_DIVIDE": 0x6F,
      "VK_OEM_1": 0xBA, "VK_OEM_PLUS": 0xBB, "VK_OEM_COMMA": 0xBC, "VK_OEM_MINUS": 0xBD, "VK_OEM_PERIOD": 0xBE,
      "VK_OEM_2": 0xBF, "VK_OEM_3": 0xC0, "VK_OEM_4": 0xDB, "VK_OEM_5": 0xDC, "VK_OEM_6": 0xDD,
      "VK_OEM_7": 0xDE, "VK_OEM_102": 0xE2}
for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789":
    VK[f"VK_{c}"] = ord(c)
for i in range(1, 25):
    VK[f"VK_F{i}"] = 0x6F + i
for i in range(10):
    VK[f"VK_NUMPAD{i}"] = 0x60 + i

params = (src / "Parameters.cpp").read_text(encoding="utf-8", errors="replace")


def table(name):
    i = params.index(name)
    body = params[params.index("{", i) + 1:]
    return body[: body.index("};")]


B = {"true": "true", "false": "false"}
keys = ["// GENERATED by tools/gen-menu-table.py from PowerEditor/src/Parameters.cpp. Do not edit.",
        "// NPP_DEFKEY(vk, commandId, ctrl, alt, shift, \"name\")"]
for m in re.finditer(r"^\s*\{\s*(VK_\w+)\s*,\s*(IDM\w*)\s*,\s*(true|false)\s*,\s*(true|false)\s*,\s*(true|false)\s*,\s*(nullptr|L\"[^\"]*\")\s*\}",
                     table("winKeyDefs[]"), re.M):
    vk, idm, c, a, s, nm = m.groups()
    if idm not in values or vk not in VK:
        continue
    nm = "" if nm == "nullptr" else nm[2:-1]
    keys.append(f'NPP_DEFKEY({VK[vk]}, {idm}, {c}, {a}, {s}, "{nm}")')
(out_dir / "DefaultShortcuts.inc").write_text("\n".join(keys) + "\n", encoding="utf-8", newline="\n")

sk = ["// GENERATED by tools/gen-menu-table.py from PowerEditor/src/Parameters.cpp. Do not edit.",
      "// NPP_SCIKEY(\"name\", SCI_ID, ctrl, alt, shift, vk, commandId or 0)"]
for m in re.finditer(r"^\s*\{\s*L\"([^\"]*)\"\s*,\s*(SCI_\w+)\s*,\s*(true|false)\s*,\s*(true|false)\s*,\s*(true|false)\s*,\s*(VK_\w+)\s*,\s*(\w+)\s*\}",
                     table("scintKeyDefs[]"), re.M):
    nm, sci, c, a, s, vk, idm = m.groups()
    if vk not in VK:
        continue
    cmdid = values.get(idm, 0) if idm != "0" else 0
    sk.append(f'NPP_SCIKEY("{nm}", {sci}, {c}, {a}, {s}, {VK[vk]}, {cmdid})')
(out_dir / "ScintillaKeys.inc").write_text("\n".join(sk) + "\n", encoding="utf-8", newline="\n")
print(f"{len(keys) - 2} default shortcuts, {len(sk) - 2} scintilla keys")

# --- language menu ids -> LangType (Notepad_plus::menuID2LangType) ------------------------------
npp = (src / "Notepad_plus.cpp").read_text(encoding="utf-8", errors="replace")
i = npp.index("LangType Notepad_plus::menuID2LangType(int cmdID)")
body = npp[i: npp.index("\n}\n", i)]
lm = ["// GENERATED by tools/gen-menu-table.py from Notepad_plus::menuID2LangType. Do not edit.",
      "// NPP_LANGCMD(commandId, LangType)"]
pending = []
for line in body.splitlines():
    pending += re.findall(r"case\s+(IDM_LANG_\w+)\s*:", line)
    m = re.search(r"return\s+(L_\w+)\s*;", line)
    if m and pending:
        for idm in pending:
            if idm in values:
                lm.append(f"NPP_LANGCMD({idm}, {m.group(1)})")
        pending = []
(out_dir / "LanguageCommands.inc").write_text("\n".join(lm) + "\n", encoding="utf-8", newline="\n")
print(f"{len(lm) - 2} language commands")
print(f"{len(values)} ids, {sum(1 for l in out if l.startswith('NPP_ITEM'))} menu items")
if unknown:
    print("skipped (non IDM ids):", " ".join(sorted(unknown)), file=sys.stderr)

# --- menu commands recorded into macros (Notepad_plus::command, "if (_recordingMacro)") ---------
i = npp_cmds = (src / "NppCommands.cpp").read_text(encoding="utf-8", errors="replace")
start = npp_cmds.index("if (_recordingMacro)")
block = npp_cmds[start: npp_cmds.index("\n}\n", start)]
recorded, pending = [], []
for line in block.splitlines():
    pending += re.findall(r"case\s+(IDM_\w+)\s*:", line)
    if "_macro.push_back(recordedMacroStep(id))" in line:
        recorded += [p for p in pending if p in values]
        pending = []
    elif re.match(r"\s*break\s*;", line) and pending and "_macro" not in line:
        pending = []  # handled by Scintilla's own macro recording (cut, copy, paste, ...)
mc = ["// GENERATED by tools/gen-menu-table.py from Notepad_plus::command (_recordingMacro). Do not edit.",
      "// NPP_MACROCMD(commandId)"]
mc += [f"NPP_MACROCMD({r})" for r in dict.fromkeys(recorded)]
(out_dir / "MacroableCommands.inc").write_text("\n".join(mc) + "\n", encoding="utf-8", newline="\n")
print(f"{len(mc) - 2} macroable menu commands")

# --- Scintilla messages accepted in macros (recordedMacroStep::isMacroable / constructor) -------
sc = (src / "WinControls/shortcut/shortcut.cpp").read_text(encoding="utf-8", errors="replace")
a = sc.index("bool recordedMacroStep::isMacroable() const")
body = sc[a: sc.index("void recordedMacroStep::PlayBack", a)]
split = body.index("case SCI_GOTOLINE")
ctor = sc[sc.index("recordedMacroStep::recordedMacroStep(int iMessage"): sc.index("// code comes from")]
mm = ["// GENERATED by tools/gen-menu-table.py from WinControls/shortcut/shortcut.cpp (recordedMacroStep). Do not edit.",
      "// NPP_MACRO_SPARAM(msg): macroable with a string parameter; NPP_MACRO_LPARAM(msg): with an integer parameter",
      "// NPP_MACRO_STRINGARG(msg): recorded lParam is a string (converted to sParam)"]
mm += [f"NPP_MACRO_SPARAM({m})" for m in re.findall(r"case (SCI_\w+)", body[:split])]
mm += [f"NPP_MACRO_LPARAM({m})" for m in re.findall(r"case (SCI_\w+)", body[split:])]
mm += [f"NPP_MACRO_STRINGARG({m})" for m in re.findall(r"case (SCI_\w+)", ctor)]
(root / "app/core/shortcut/MacroMessages.inc").write_text("\n".join(mm) + "\n", encoding="utf-8", newline="\n")
