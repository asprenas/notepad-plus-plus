#!/usr/bin/env python3
"""Generates app/plugin-api/include/npp_msgs.h from upstream Notepad_plus_msgs.h (phase 7).

The generated header has the NPPM_* message numbers and their argument constants, plus the
LangType / winVer / Platform enums, without <windows.h> (WM_USER is a plain number) so that
ported plugins compile on every platform. NPPN_* codes live in npp_plugin_api.h.

Usage: python tools/gen-npp-msgs.py   (from the repository root)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "PowerEditor/src/MISC/PluginsManager/Notepad_plus_msgs.h"
OUT = ROOT / "app/plugin-api/include/npp_msgs.h"

DEFINE = re.compile(r"^\s*#\s*define\s+([A-Za-z_][A-Za-z0-9_]*)\s+(.*?)\s*(//.*)?$")
PLAIN_ENUMS = ("enum LangType", "enum winVer", "enum Platform")


def main():
    lines = SRC.read_text(encoding="utf-8").splitlines()
    out = []
    i = 0
    count = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()
        if stripped.startswith(PLAIN_ENUMS):
            block = [stripped]
            while not block[-1].rstrip().endswith("};"):
                i += 1
                block.append(lines[i].strip())
            body = " ".join(b.rstrip("\\").strip() for b in block if not b.startswith("//"))
            out.append("#ifndef NPP_COMPAT_NO_ENUMS")
            out.append(body)
            out.append("#endif")
            out.append("")
        else:
            m = DEFINE.match(line)
            if m and not m.group(1).startswith("NPPN_"):
                name, value = m.group(1), m.group(2).strip()
                value = value.replace("WM_USER", "NPP_COMPAT_WM_USER")
                out.append(f"#define {name} {value}")
                count += 1
        i += 1
    header = [
        "/* Generated by tools/gen-npp-msgs.py from upstream Notepad_plus_msgs.h (v8.9.8.1). Do not edit. */",
        "/* NPPM_* message numbers for npp_compat.h; see docs/plugin-api-nppm.md for what is supported. */",
        "#ifndef NPP_MSGS_H",
        "#define NPP_MSGS_H",
        "",
        "#define NPP_COMPAT_WM_USER 0x0400",
        "",
    ]
    OUT.write_text("\n".join(header + out + ["", "#endif /* NPP_MSGS_H */", ""]), encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {count} defines")


if __name__ == "__main__":
    sys.exit(main())
