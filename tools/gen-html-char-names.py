"""Generates app/ui/panels/HtmlCharNames.inc from upstream AsciiListView::getHtmlName
(PowerEditor/src/WinControls/AnsiCharPanel/asciiListView.cpp).

Run: python -I tools/gen-html-char-names.py
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "PowerEditor/src/WinControls/AnsiCharPanel/asciiListView.cpp").read_text(encoding="utf-8")
body = src[src.index("AsciiListView::getHtmlName"):src.index("AsciiListView::getHtmlNumber")]
pairs = re.findall(r'case\s+(\d+):\s*return\s+L"([^"]*)";', body)
out = ["// GENERATED by tools/gen-html-char-names.py from upstream asciiListView.cpp (getHtmlName). Do not edit.",
       "// NPP_HTML_NAME(byte value in Windows-1252, entity)"]
for value, name in pairs:
    out.append(f'NPP_HTML_NAME({value}, "{name}")')
(root / "app/ui/panels/HtmlCharNames.inc").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(f"{len(pairs)} names")
