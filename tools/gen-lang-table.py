"""Generates app/core/lang/LangTypes.inc from the upstream sources (phase 1, lang module).

Usage (from the repository root):  python -I tools/gen-lang-table.py

Sources:
  PowerEditor/src/MISC/PluginsManager/Notepad_plus_msgs.h   enum LangType (numeric values are part
                                                            of session.xml / plugin API)
  PowerEditor/src/ScintillaComponent/ScintillaEditView.cpp  _langNameInfoArray (names, lexer ids)
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
msgs = (root / "PowerEditor/src/MISC/PluginsManager/Notepad_plus_msgs.h").read_text(encoding="utf-8", errors="replace")
enum = re.search(r"enum LangType\s*\{(.*?)\};", msgs, re.S).group(1)
enum = re.sub(r"//[^\n]*", "", enum).replace("\\", "")
names = [x.strip() for x in enum.split(",") if x.strip()]

src = (root / "PowerEditor/src/ScintillaComponent/ScintillaEditView.cpp").read_text(encoding="utf-8", errors="replace")
arr = src[src.index("LanguageNameInfo ScintillaEditView::_langNameInfoArray"):]
arr = arr[: arr.index("};")]
rows = re.findall(r'\{L"([^"]*)",\s*L"([^"]*)",\s*L"([^"]*)",\s*(L_\w+),\s*(nullptr|"[^"]*")\}', arr)

if [r[3] for r in rows] != names:
    sys.exit(f"enum / table mismatch: {len(rows)} rows, {len(names)} enum values")


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


out = [
    "// GENERATED by tools/gen-lang-table.py from upstream v8.9.8.1",
    "// (Notepad_plus_msgs.h enum LangType, ScintillaEditView::_langNameInfoArray). Do not edit.",
    "// NPP_LANG(enumName, langName, shortName, longName, lexilla lexer name or nullptr)",
]
for lang, short, long_, lid, lex in rows:
    out.append(f'NPP_LANG({lid}, "{esc(lang)}", "{esc(short)}", "{esc(long_)}", {lex})')

dest = root / "app/core/lang/LangTypes.inc"
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(f"{len(rows)} languages written to {dest.relative_to(root)}")
