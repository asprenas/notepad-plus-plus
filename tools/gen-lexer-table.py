"""Generates app/core/lang/LexerSpecs.inc from upstream ScintillaEditView (phase 1, P1 lang module).

Usage (from the repository root):  python -I tools/gen-lexer-table.py

For every `case L_xxx:` of ScintillaEditView::defineDocType the called setXxxLexer() function is
resolved. Functions defined inline in ScintillaEditView.h that only call
    setLexer(L_X, LIST_a | LIST_b ..., [baseSubStyleID, [numSubStyles]])
and SCI_SETPROPERTY are emitted as data:
    NPP_LEXER_GENERIC(L_X, listMask, "baseSubStyleID or empty", numSubStyles, "k1=v1;k2=v2")
Everything else is emitted as
    NPP_LEXER_SPECIAL(L_X, "setXxxLexer")
and implemented by hand in LexerSpecs.cpp.
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
cpp = (root / "PowerEditor/src/ScintillaComponent/ScintillaEditView.cpp").read_text(encoding="utf-8", errors="replace")
hdr = (root / "PowerEditor/src/ScintillaComponent/ScintillaEditView.h").read_text(encoding="utf-8", errors="replace")

# --- defineDocType switch: case labels -> function ------------------------------------------
start = cpp.index("void ScintillaEditView::defineDocType")
body = cpp[start:]
body = body[: body.index("\n}\n")]
sw = body[body.index("switch (typeDoc)"):]
cases = {}
pending = []
for line in sw.splitlines():
    line = re.sub(r"//.*", "", line)
    for lab in re.findall(r"case\s+(L_\w+)\s*:", line):
        pending.append(lab)
    m = re.search(r"\b(set\w+Lexer)\s*\(([^)]*)\)", line)
    if m and pending:
        for lab in pending:
            cases.setdefault(lab, (m.group(1), m.group(2).strip()))
    if "break;" in line:
        pending = []

# --- inline header bodies ------------------------------------------------------------------
inline = {}
for m in re.finditer(r"void\s+(set\w+Lexer)\s*\(\s*\)\s*(?:const\s*)?\{", hdr):
    i = m.end()
    depth = 1
    while depth:
        depth += {"{": 1, "}": -1}.get(hdr[i], 0)
        i += 1
    inline[m.group(1)] = hdr[m.end(): i - 1]

LIST = {f"LIST_{n}": 1 << n for n in range(9)}
LIST["LIST_NONE"] = 0

out = [
    "// GENERATED by tools/gen-lexer-table.py from upstream v8.9.8.1 ScintillaEditView. Do not edit.",
    "// NPP_LEXER_GENERIC(langType, keywordListMask, subStyleBaseStyle or -1, numSubStyles, \"prop=value;...\")",
    "// NPP_LEXER_SPECIAL(langType, \"upstream function\")   -> hand written in LexerSpecs.cpp",
]
generic = special = 0
for lab, (func, args) in sorted(cases.items(), key=lambda kv: kv[0]):
    b = inline.get(func)
    simple = False
    if b is not None and not args:
        code = re.sub(r"//[^\n]*", "", b)
        calls = re.findall(r"\bsetLexer\s*\(([^;]*)\);", code)
        props = re.findall(r'SCI_SETPROPERTY,\s*reinterpret_cast<WPARAM>\("([^"]+)"\),\s*reinterpret_cast<LPARAM>\("([^"]*)"\)', code)
        stmts = [s.strip() for s in code.split(";") if s.strip()]
        others = [s for s in stmts if not s.startswith("setLexer(") and "SCI_SETPROPERTY" not in s]
        if len(calls) == 1 and not others:
            parts = [p.strip() for p in calls[0].split(",")]
            mask = 0
            for tok in re.split(r"\s*\|\s*", parts[1]):
                mask |= LIST[tok]
            base = parts[2] if len(parts) > 2 else ""
            nsub = parts[3] if len(parts) > 3 else ("8" if base else "0")
            prop = ";".join(f"{k}={v}" for k, v in props)
            out.append(f'NPP_LEXER_GENERIC({parts[0]}, 0x{mask:03X}, {base or "-1"}, {nsub}, "{prop}")')
            simple = True
            generic += 1
    if not simple:
        out.append(f'NPP_LEXER_SPECIAL({lab}, "{func}({args})")')
        special += 1

dest = root / "app/core/lang/LexerSpecs.inc"
dest.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(f"{generic} generic, {special} special lexer setups -> {dest.relative_to(root)}")
