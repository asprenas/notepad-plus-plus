#!/usr/bin/env python3
"""Generates app/ui/menu/ToolbarButtons.inc from upstream Notepad_plus.cpp toolBarIcons[] and
Notepad_plus.rc (icon resource -> file). Columns: command, light regular (+disabled), light filled
(+disabled), dark regular (+disabled), dark filled (+disabled), standard bitmap, custom icon name
(toolbarButtonsConf.xml <ToolBarIcons>)."""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "PowerEditor" / "src"

CUSTOM = ["new", "open", "save", "save-all", "close", "close-all", "print", None, "cut", "copy", "paste", None,
          "undo", "redo", None, "find", "replace", None, "zoom-in", "zoom-out", None, "sync-vertical",
          "sync-horizontal", None, "word-wrap", "all-chars", "indent-guide", None, "udl-dlg", "doc-map", "doc-list",
          "function-list", "folder-as-workspace", None, "monitoring", None, "record", "stop-record", "playback",
          "playback-multiple", "save-macro"]

rc = (SRC / "Notepad_plus.rc").read_text(encoding="utf-8", errors="replace")
res = dict(re.findall(r'^\s*(\w+)\s+(?:ICON|BITMAP)\s+"([^"]+)"', rc, re.M))

cpp = (SRC / "Notepad_plus.cpp").read_text(encoding="utf-8", errors="replace")
body = cpp[cpp.index("toolBarIcons[]{"):]
body = body[:body.index("};")]
rows = []
for m in re.finditer(r"^\s*\{([^}]*)\}", body, re.M):
    cols = [c.strip() for c in m.group(1).split(",")]
    rows.append(cols)

out = ["// GENERATED by tools/gen-toolbar-table.py from PowerEditor/src/Notepad_plus.cpp (toolBarIcons)",
       "// and Notepad_plus.rc. Do not edit. Paths are relative to PowerEditor/src/icons.", ""]
assert len(rows) == len(CUSTOM), (len(rows), len(CUSTOM))
for cols, custom in zip(rows, CUSTOM):
    if cols[0] == "0":
        out.append("NPP_TB_SEPARATOR()")
        continue
    files = []
    for c in cols[1:10]:
        f = res[c].replace("\\\\", "/").replace("\\", "/")
        assert f.startswith("icons/"), f
        files.append('"%s"' % f[len("icons/"):])
    out.append("NPP_TB_BUTTON(%s, %s, \"%s\")" % (cols[0], ", ".join(files), custom))
(ROOT / "app/ui/menu/ToolbarButtons.inc").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(len(rows), "entries")
