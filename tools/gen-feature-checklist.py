"""Generates docs/feature-checklist.md: every main menu command, its owning phase and whether
the Qt UI registers a handler for it (P0-17; used by the phase completion criteria).

Usage (from the repository root):  python -I tools/gen-feature-checklist.py
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
menu_dir = root / "app/ui/menu"
ui_dir = root / "app/ui"

values = {m.group(1): int(m.group(2)) for m in re.finditer(r"inline constexpr int (\w+) = (\d+);",
                                                           (menu_dir / "CommandIds.h").read_text(encoding="utf-8"))}

# Handlers: IDM_ names used in setHandler calls / loops of the UI sources
handled = set()
src = "".join(p.read_text(encoding="utf-8") for p in ui_dir.glob("*.cpp"))
handled |= set(re.findall(r"\b(IDM_\w+)\b", src))
handled |= set(re.findall(r"NPP_LANGCMD\((IDM_\w+)", (menu_dir / "LanguageCommands.inc").read_text(encoding="utf-8")))
ranges = []  # (first, last) id ranges registered in loops
if "IDM_VIEW_TAB1 + i" in src:
    ranges.append((values["IDM_VIEW_TAB1"], values["IDM_VIEW_TAB1"] + 8))
# loops registering "FIRST + i" / "FIRST + i * 2" / "(... ? A : B) + 1 + level"
for first, count, step in [("IDM_SEARCH_MARKALLEXT1", 5, 2), ("IDM_SEARCH_UNMARKALLEXT1", 5, 2), ("IDM_SEARCH_MARKONEEXT1", 5, 1),
                           ("IDM_SEARCH_GONEXTMARKER1", 5, 1), ("IDM_SEARCH_GOPREVMARKER1", 5, 1)]:
    if re.search(re.escape(first) + r" \+ i( \* 2)?", src):
        handled.update(n for n, v in values.items() if v in range(values[first], values[first] + count * step, step))
if "(collapse ? IDM_VIEW_FOLD : IDM_VIEW_UNFOLD) + 1 + level" in src:
    for base in ("IDM_VIEW_FOLD", "IDM_VIEW_UNFOLD"):
        handled.update(n for n, v in values.items() if values[base] + 1 <= v <= values[base] + 8 and n.startswith(base + "_"))
if "IDM_FORMAT_ENCODE + i" in src:
    ranges.append((values["IDM_FORMAT_ENCODE"], values.get("IDM_FORMAT_ENCODE_END", values["IDM_FORMAT_ENCODE"] + 60)))


def is_handled(name):
    if name in handled:
        return True
    v = values.get(name)
    return v is not None and any(a <= v <= b for a, b in ranges)


# Owning phase per top-level menu (plan docs); exceptions by id prefix
PHASE = {"File": 2, "Edit": 3, "Search": 3, "View": 2, "Encoding": 2, "Language": 2, "Settings": 4,
         "Tools": 5, "Macro": 3, "Run": 5, "Plugins": 7, "Window": 5, "?": 5}
OVERRIDE = [(r"^IDM_SEARCH_(GOTOLINE|TOGGLE_BOOKMARK|CLEAR_BOOKMARKS)$", 2),
            (r"^IDM_EDIT_(UNDO|REDO|CUT|COPY|PASTE|DELETE|SELECTALL)$", 2),
            (r"^IDM_VIEW_(SWITCHTO_|FUNC|DOC_MAP|PROJECT|PANEL|MONITOR|SUMMARY|FILESWITCHER)", 5),
            (r"^IDM_VIEW_(DOCLIST|FILEBROWSER)$", 5),
            (r"^IDM_VIEW_(FOLD|UNFOLD|HIDELINES|SYNSCROLL)", 3),
            (r"^IDM_(FILE_PRINT|FILE_PRINTNOW)", 5),
            (r"^IDM_LANG_(USER_DLG|OPENUDLDIR|UDLCOLLECTION)", 5),
            (r"^IDM_LANGSTYLE_CONFIG_DLG$", 4),
            # tab colours / pinned tabs follow the TabSetting options and themes (phase 4)
            (r"^IDM_(VIEW_TAB_COLOUR_|FILE_CLOSEALL_BUT_PINNED|PINTAB)", 4),
            # non-printing character representations come with the Editing settings page (phase 4)
            (r"^IDM_VIEW_NPC", 4),
            # panels (phase 5): Character Panel, Clipboard History
            (r"^IDM_EDIT_(CHAR_PANEL|CLIPBOARDHISTORY_PANEL)$", 5),
            # Change Search Engine opens the Preferences dialog (phase 4)
            (r"^IDM_EDIT_CHANGESEARCHENGINE$", 4)]


def phase_of(top, name):
    for pat, ph in OVERRIDE:
        if re.search(pat, name):
            return ph
    return PHASE.get(top, 5)


rows, stack, seen = [], [], set()
for line in (menu_dir / "MainMenu.inc").read_text(encoding="utf-8").splitlines():
    m = re.match(r'NPP_POPUP_BEGIN\("(.*)"\)', line)
    if m:
        stack.append(m.group(1).replace("&", ""))
        continue
    if line.startswith("NPP_POPUP_END"):
        stack.pop()
        continue
    m = re.match(r'NPP_ITEM\("(.*)", (\w+)\)', line)
    if not m or not stack or stack[0] == "▼":
        continue
    text, name = m.group(1).replace("&", "").replace('\\"', '"').split("\\t")[0], m.group(2)
    top = stack[0]
    key = (top, name)
    if key in seen:  # compact and full Language menus repeat ids
        continue
    seen.add(key)
    rows.append((top, " > ".join(stack[1:] + [text]), name, phase_of(top, name), is_handled(name)))

out = ["# 기능 체크리스트 (메뉴 기준)", "",
       "> GENERATED by `tools/gen-feature-checklist.py` (메뉴 = `app/ui/menu/MainMenu.inc`, 구현 = `app/ui/*.cpp`에 등록된 핸들러).",
       "> 다시 생성: `python -I tools/gen-feature-checklist.py`. 담당 단계는 계획서 기준 기본값이며 스크립트의 `PHASE`/`OVERRIDE`에서 조정한다.", ""]
out += ["## 단계별 요약", "", "| 단계 | 항목 | 구현 | 비율 |", "|---|---|---|---|"]
for ph in sorted({r[3] for r in rows}):
    items = [r for r in rows if r[3] == ph]
    done = sum(r[4] for r in items)
    out.append(f"| {ph} | {len(items)} | {done} | {100 * done // len(items)}% |")
total_done = sum(r[4] for r in rows)
out.append(f"| 전체 | {len(rows)} | {total_done} | {100 * total_done // len(rows)}% |")
out.append("")
for top in dict.fromkeys(r[0] for r in rows):
    out += [f"## {top}", "", "| | 메뉴 | ID | 단계 |", "|---|---|---|---|"]
    for t, path, name, ph, ok in rows:
        if t == top:
            out.append(f"| {'[x]' if ok else '[ ]'} | {path.replace('|', '/')} | `{name}` | {ph} |")
    out.append("")
(root / "docs/feature-checklist.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
print("\n".join(out[5:5 + 4 + len({r[3] for r in rows}) + 1]))
missing2 = [f"{r[1]} ({r[2]})" for r in rows if r[3] == 2 and not r[4]]
print("phase 2 missing:", len(missing2))
for m_ in missing2:
    print("  ", m_)
